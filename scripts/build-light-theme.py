from pathlib import Path
import re, colorsys
root=Path(__file__).resolve().parents[1]/'dist'
def color(m):
 h=m[0][1:]
 if len(h) not in (3,6):return m[0]
 if len(h)==3:h=''.join(c*2 for c in h)
 rgb=[int(h[i:i+2],16)/255 for i in (0,2,4)];hue,l,s=colorsys.rgb_to_hls(*rgb)
 if l<.23 and (s<.48 or l<.09):nl=.98-l*.58
 elif s<.25 and l>.36:nl=max(.12,1-l)
 elif s<.25:nl=.74
 else:return m[0]
 return '#'+''.join(f'{round(c*255):02x}' for c in colorsys.hls_to_rgb(hue,nl,min(s,.12)))
parts=[]
for name in ['styles.css','system-settings.css','group-manager.css','offline-license.css']:
 s=(root/name).read_text();s=re.sub(r'#[0-9a-fA-F]{3,8}\b',color,s);s=s.replace('color-scheme:dark','color-scheme:light');parts.append(s)
(root/'light-theme.css').write_text('/* Generated by scripts/build-light-theme.py. Enabled only in light mode. */\n'+'\n'.join(parts)+'\n:root{--bg:#f5f7fa;--panel:#ffffff;--text:#202733;--muted:#657184;--line:#d5dde7;color-scheme:light}dialog{box-shadow:0 18px 60px #17233526}dialog::backdrop{background:#18263755}.settings-card{border-radius:12px}.button.blue{color:#fff}.gm-tabs button[aria-pressed="true"]{color:#fff}.nt-accounts>button[aria-pressed="true"]{background:#e5efff!important;color:#164b9c!important}.settings-nav-button.active{background:#e8f0ff;color:#155eef}.button.quiet{color:#26364b}.settings-head-icon,.rail-button svg{color:#276bff}\n')
